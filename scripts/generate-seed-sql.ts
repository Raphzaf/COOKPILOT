/**
 * Generates database/seeds/*.sql from the TypeScript seed data (src/data/seed), so demo mode
 * and a real Supabase project always start from exactly the same catalogue.
 *
 *   npm run db:seed:generate
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { SEED_BRANDS, SEED_CATEGORIES, SEED_DEVICES, seedId } from "../src/data/seed/devices";
import { buildSeedKnowledge } from "../src/data/seed/knowledge";
import { SEED_RECIPES, localizeSeedRecipe } from "../src/data/seed/recipes";
import { LOCALES } from "../src/lib/domain/types";
import { chunkText, contentHash } from "../src/lib/rag/chunk";

const q = (value: string | null | undefined) => (value == null ? "null" : `'${value.replace(/'/g, "''")}'`);
const j = (value: unknown) => `${q(JSON.stringify(value))}::jsonb`;
const n = (value: number | null | undefined) => (value == null ? "null" : String(value));
const arr = (values: string[]) => (values.length ? `array[${values.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const HEADER = (title: string) => `-- CookPilot seed · ${title}\n-- GENERATED by scripts/generate-seed-sql.ts — do not edit by hand. Safe to run more than once.\n`;

function catalogue(): string {
  const out = [HEADER("appliance catalogue"), "begin;\n"];
  for (const b of SEED_BRANDS) out.push(`insert into public.brands (id, slug, name, manufacturer) values (${q(b.id)}, ${q(b.slug)}, ${q(b.name)}, ${q(b.manufacturer)}) on conflict (id) do nothing;`);
  for (const c of SEED_CATEGORIES) out.push(`insert into public.device_categories (id, slug, name, description) values (${q(c.id)}, ${q(c.slug)}, ${j(c.name)}, ${j(c.description)}) on conflict (id) do nothing;`);
  for (const d of SEED_DEVICES) {
    out.push(
      `\ninsert into public.device_models (id, slug, brand_id, category_id, name, model_number, region, description, image_url, specs, missing_info, verification_status, last_verified_at, published)\nvalues (${q(d.id)}, ${q(d.slug)}, ${q(d.brand.id)}, ${q(d.category.id)}, ${q(d.name)}, ${q(d.modelNumber)}, ${q(d.region)}, ${j(d.description)}, ${q(d.imageUrl)}, ${j(d.specs)}, ${j(d.missingInfo)}, ${q(d.verificationStatus)}, ${q(d.lastVerifiedAt)}, ${d.published})\non conflict (id) do nothing;`,
    );
    d.capabilities.forEach((c, position) =>
      out.push(
        `insert into public.device_capabilities (id, device_model_id, kind, key, name, temp_min, temp_max, temp_unit, levels, notes, position) values (${q(c.id)}, ${q(d.id)}, ${q(c.kind)}, ${q(c.key)}, ${j(c.name)}, ${n(c.tempMin)}, ${n(c.tempMax)}, ${q(c.tempUnit)}, ${arr(c.levels)}, ${c.notes ? j(c.notes) : "null"}, ${position}) on conflict (id) do nothing;`,
      ),
    );
    for (const s of d.sources) out.push(`insert into public.device_sources (id, device_model_id, title, url, kind, accessed_at) values (${q(s.id)}, ${q(d.id)}, ${q(s.title)}, ${q(s.url)}, ${q(s.kind)}, ${q(s.accessedAt)}) on conflict (id) do nothing;`);
  }
  out.push("\ncommit;\n");
  return out.join("\n");
}

function recipes(): string {
  const out = [HEADER("demonstration recipes (is_demo = true, never 'verified')"), "begin;\n"];
  SEED_RECIPES.forEach((seed, index) => {
    const versionId = seedId("0e00", index + 1);
    const en = localizeSeedRecipe(seed, "en");
    out.push(
      `\n-- ${en.title}\ninsert into public.recipes (id, slug, owner_id, status, illustration, category, cuisine, dietary, difficulty, device_category, programs, provenance, author_name, is_demo)\nvalues (${q(seed.id)}, ${q(seed.slug)}, null, 'published', ${q(seed.illustration)}, ${q(seed.category)}, ${q(seed.cuisine)}, ${arr(seed.dietary)}, ${q(seed.difficulty)}, ${q(seed.deviceCategory)}, ${arr(seed.programs)}, ${q(seed.provenance)}, 'CookPilot', true)\non conflict (id) do nothing;`,
    );
    out.push(`insert into public.recipe_versions (id, recipe_id, version, servings, prep_minutes, cook_minutes) values (${q(versionId)}, ${q(seed.id)}, 1, ${seed.servings}, ${seed.prepMinutes}, ${seed.cookMinutes}) on conflict (id) do nothing;`);
    out.push(`update public.recipes set current_version_id = ${q(versionId)} where id = ${q(seed.id)} and current_version_id is null;`);
    for (const locale of LOCALES) {
      const r = localizeSeedRecipe(seed, locale);
      out.push(`insert into public.recipe_translations (recipe_id, locale, title, description, accessories, safety_notes, source_note) values (${q(seed.id)}, ${q(locale)}, ${q(r.title)}, ${q(r.description)}, ${j(r.accessories)}, ${j(r.safetyNotes)}, ${q(r.sourceNote)}) on conflict (recipe_id, locale) do nothing;`);
      r.ingredients.forEach((i, pos) =>
        out.push(`insert into public.recipe_ingredients (version_id, locale, position, name, quantity, unit, note, optional) values (${q(versionId)}, ${q(locale)}, ${pos + 1}, ${q(i.name)}, ${n(i.quantity)}, ${q(i.unit)}, ${q(i.note)}, ${i.optional}) on conflict (version_id, locale, position) do nothing;`),
      );
      for (const s of r.steps)
        out.push(`insert into public.recipe_steps (version_id, locale, position, instruction, program, level, temperature_c, duration_seconds, tip) values (${q(versionId)}, ${q(locale)}, ${s.position}, ${q(s.instruction)}, ${q(s.program)}, ${q(s.level)}, ${n(s.temperatureC)}, ${n(s.durationSeconds)}, ${q(s.tip)}) on conflict (version_id, locale, position) do nothing;`);
    }
    for (const modelId of seed.compatibleModelIds) out.push(`insert into public.recipe_compatibility (recipe_id, device_model_id, tested) values (${q(seed.id)}, ${q(modelId)}, false) on conflict do nothing;`);
  });
  out.push("\ncommit;\n");
  return out.join("\n");
}

function knowledge(): string {
  const out = [HEADER("knowledge base (text only — embeddings are added by `npm run knowledge:ingest`)"), "begin;\n"];
  buildSeedKnowledge().forEach((doc, index) => {
    const id = seedId("d0c0", index + 1);
    out.push(
      `\ninsert into public.knowledge_documents (id, title, source, source_url, manufacturer, model_number, language, doc_type, published_at, verification_status, rights_note, content_hash)\nvalues (${q(id)}, ${q(doc.title)}, ${q(doc.source)}, ${q(doc.sourceUrl)}, ${q(doc.manufacturer)}, ${q(doc.modelNumber)}, ${q(doc.language)}, ${q(doc.docType)}, ${q(doc.publishedAt)}, ${q(doc.verificationStatus)}, ${q(doc.rightsNote)}, ${q(contentHash(doc.content))})\non conflict do nothing;`,
    );
    chunkText(doc.content).forEach((content, position) =>
      out.push(`insert into public.knowledge_chunks (document_id, position, content) select ${q(id)}, ${position}, ${q(content)} where exists (select 1 from public.knowledge_documents where id = ${q(id)}) on conflict (document_id, position) do nothing;`),
    );
  });
  out.push("\ncommit;\n");
  return out.join("\n");
}

const dir = path.resolve(__dirname, "../database/seeds");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "0001_catalogue.sql"), catalogue());
writeFileSync(path.join(dir, "0002_demo_recipes.sql"), recipes());
writeFileSync(path.join(dir, "0003_knowledge.sql"), knowledge());
console.log("Seed SQL written to database/seeds/");
